#!/usr/bin/env bash
# Regenerates all protocol code. Called by `make proto`.
#   1. Go code via buf + protoc-gen-go into server/internal/pb/
#   2. protocol_version constants for Go and GDScript from proto/PROTOCOL_VERSION
#   3. GDScript code via godobuf into client/net/pb/ (one *_pb.gd per .proto)
#   4. Golden vectors into proto/testdata/
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
GODOT="${1:-godot}"
cd "$ROOT"

version="$(tr -d '[:space:]' <proto/PROTOCOL_VERSION)"
if ! [[ "$version" =~ ^[1-9][0-9]*$ ]]; then
  echo "proto/PROTOCOL_VERSION must be a positive integer, got '$version'" >&2; exit 1
fi

echo "proto: Go"
rm -f server/internal/pb/*.pb.go
buf generate proto --template proto/buf.gen.yaml
cat >server/internal/pb/protocol_version.go <<GO
// Code generated by make proto from proto/PROTOCOL_VERSION. DO NOT EDIT.

package pb

// ProtocolVersion is the wire protocol version. Clients and servers with
// different versions refuse to talk. See proto/README.md.
const ProtocolVersion = $version
GO

echo "proto: GDScript (godobuf)"
if [[ ! -f client/addons/godobuf/godobuf_cmdln.gd ]]; then
  echo "godobuf is not installed; run make setup" >&2; exit 1
fi
mkdir -p client/net/pb
# Keep *.uid files: Godot assigns them once and they must stay stable.
rm -f client/net/pb/*_pb.gd
cat >client/net/pb/protocol_version.gd <<GD
# Code generated by make proto from proto/PROTOCOL_VERSION. DO NOT EDIT.
class_name ProtocolVersion
extends RefCounted
## The wire protocol version. See proto/README.md.

const CURRENT: int = $version
GD
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
while IFS= read -r src; do
  name="$(basename "$src" .proto)"
  out="client/net/pb/${name}_pb.gd"
  log="$("$GODOT" --headless --path client -s addons/godobuf/godobuf_cmdln.gd \
    --input="$ROOT/$src" --output="$tmp/${name}.gd" 2>&1)" || true
  if [[ ! -s "$tmp/${name}.gd" ]]; then
    echo "$log" >&2; echo "godobuf failed for $src" >&2; exit 1
  fi
  {
    echo "# Code generated by make proto from $src with godobuf. DO NOT EDIT."
    echo "#"
    cat "$tmp/${name}.gd"
  } >"$out"
  echo "  $src -> $out"
done < <(find proto/lorehallow -name '*.proto' | sort)

echo "proto: golden vectors"
(cd server && go run ./cmd/lorehallow-protovectors -out ../proto/testdata)
